# 功能：读取数据 RAM 中的五个整数，求和并把结果写入数组后面的一个字。
# 默认输入：1、2、3、4、5；结果为 15。
# x1 为字节地址指针，x2 为剩余元素数，x3 为累加和，x4 为当前元素。
# 本文件与测试平台内置机器码一致，演示不需要额外构建固件。

    addi x1, x0, 0       # 数组从数据地址 0 开始
    addi x2, x0, 5       # 共五个元素
    addi x3, x0, 0       # 累加和初始化为零

sum_loop:
    lw   x4, 0(x1)       # 读取当前元素
    add  x3, x3, x4      # 累加；紧跟加载，展示加载后使用的停顿
    addi x1, x1, 4       # 每个整数占四字节，指针移到下一个元素
    addi x2, x2, -1      # 剩余元素数减一
    bne  x2, x0, sum_loop # 未处理完则继续循环，分支使用刚计算的计数值

    sw   x3, 20(x0)      # 把求和结果写入数据地址 20，即数组后的一个字
    addi x5, x0, 1       # 完成标志，测试平台在此核对结果并结束
