#!/usr/bin/env python3
"""Convert an analyzer capture (binary or CSV) to a GTKWave-compatible VCD."""

from __future__ import annotations

import argparse
import csv
from pathlib import Path


def read_capture(path: Path, input_format: str = "auto") -> list[int]:
    if input_format == "auto":
        input_format = "csv" if path.suffix.lower() == ".csv" else "binary"
    if input_format == "binary":
        return list(path.read_bytes())
    values: list[int] = []
    with path.open(newline="") as stream:
        for row in csv.reader(stream):
            if not row or row[0].strip().lower() in {"sample", "index"}:
                continue
            token = row[-1].strip()
            values.append(int(token, 0) & 0xFF)
    return values


def write_csv(samples: list[int], path: Path) -> None:
    with path.open("w", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(["index", "sample"])
        writer.writerows(
            (index, f"0x{sample:02x}") for index, sample in enumerate(samples)
        )


def write_vcd(samples: list[int], path: Path, sample_rate: int = 100_000_000) -> None:
    if sample_rate <= 0:
        raise ValueError("sample_rate must be positive")
    step_ns = max(1, round(1_000_000_000 / sample_rate))
    identifiers = [chr(ord("!") + channel) for channel in range(8)]
    with path.open("w", newline="\n") as stream:
        stream.write("$date generated by capture_dump.py $end\n")
        stream.write("$version RV32 Digital Analyzer v1.0 $end\n")
        stream.write("$timescale 1ns $end\n$scope module analyzer $end\n")
        for channel, ident in enumerate(identifiers):
            stream.write(f"$var wire 1 {ident} ch{channel} $end\n")
        stream.write("$upscope $end\n$enddefinitions $end\n$dumpvars\n")
        previous = None
        for index, sample in enumerate(samples):
            stream.write(f"#{index * step_ns}\n")
            if previous is None:
                changed = 0xFF
            else:
                changed = sample ^ previous
            for channel, ident in enumerate(identifiers):
                if changed & (1 << channel):
                    stream.write(f"{(sample >> channel) & 1}{ident}\n")
            previous = sample
        stream.write("$dumpoff\n$end\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("--format", choices=("auto", "binary", "csv"), default="auto")
    parser.add_argument(
        "--rate", type=int, default=100_000_000, help="samples per second"
    )
    args = parser.parse_args()
    samples = read_capture(args.input, args.format)
    write_vcd(samples, args.output, args.rate)
    print(f"VCD PASS: {len(samples)} samples -> {args.output}")


if __name__ == "__main__":
    main()
