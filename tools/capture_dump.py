#!/usr/bin/env python3
"""Decode RV32 Real-Time Scope captures and export single-channel CSV/VCD."""

from __future__ import annotations

import argparse
import csv
import struct
from dataclasses import dataclass
from pathlib import Path

HEADER = struct.Struct("<4sBBHIHIII")


@dataclass(frozen=True)
class CaptureHeader:
    version: int
    flags: int
    sample_count: int
    sample_div: int
    trigger_index: int
    period_ticks: int
    high_ticks: int
    frequency_hz: int

    @property
    def trigger_edge(self) -> str:
        return "falling" if self.flags & 1 else "rising"


def crc16_modbus(data: bytes, initial: int = 0xFFFF) -> int:
    """Match the CPU's CRC16.B instruction and UART transport byte order."""
    crc = initial
    for byte in data:
        crc ^= byte
        for _ in range(8):
            crc = (crc >> 1) ^ 0xA001 if crc & 1 else crc >> 1
    return crc & 0xFFFF


def unpack_samples(packed: bytes, sample_count: int) -> list[int]:
    if sample_count < 0 or len(packed) * 8 < sample_count:
        raise ValueError("packed capture is shorter than sample_count")
    return [
        (packed[index >> 3] >> (index & 7)) & 1
        for index in range(sample_count)
    ]


def pack_samples(samples: list[int]) -> bytes:
    packed = bytearray((len(samples) + 7) // 8)
    for index, sample in enumerate(samples):
        if sample & 1:
            packed[index >> 3] |= 1 << (index & 7)
    return bytes(packed)


def parse_capture_packet(packet: bytes) -> tuple[CaptureHeader, list[int]]:
    if len(packet) < HEADER.size + 2:
        raise ValueError("capture packet is truncated")
    fields = HEADER.unpack_from(packet)
    magic, version, flags, count, sample_div, trigger_index, period, high, freq = fields
    if magic != b"CAP2" or version != 2:
        raise ValueError("unsupported capture packet")
    if count != 4096:
        raise ValueError(f"unexpected sample count: {count}")
    if sample_div < 1:
        raise ValueError("sample_div must be positive")
    payload_size = (count + 7) // 8
    expected_size = HEADER.size + payload_size + 2
    if len(packet) != expected_size:
        raise ValueError(
            f"capture packet size mismatch: {len(packet)} != {expected_size}"
        )
    expected_crc = struct.unpack_from("<H", packet, len(packet) - 2)[0]
    actual_crc = crc16_modbus(packet[:-2])
    if actual_crc != expected_crc:
        raise ValueError(
            f"capture CRC mismatch: received 0x{expected_crc:04x}, "
            f"calculated 0x{actual_crc:04x}"
        )
    header = CaptureHeader(
        version=version,
        flags=flags,
        sample_count=count,
        sample_div=sample_div,
        trigger_index=trigger_index,
        period_ticks=period,
        high_ticks=high,
        frequency_hz=freq,
    )
    payload = packet[HEADER.size : HEADER.size + payload_size]
    return header, unpack_samples(payload, count)


def build_capture_packet(header: CaptureHeader, samples: list[int]) -> bytes:
    if len(samples) != header.sample_count:
        raise ValueError("sample list length does not match header")
    prefix = HEADER.pack(
        b"CAP2",
        header.version,
        header.flags,
        header.sample_count,
        header.sample_div,
        header.trigger_index,
        header.period_ticks,
        header.high_ticks,
        header.frequency_hz,
    ) + pack_samples(samples)
    return prefix + struct.pack("<H", crc16_modbus(prefix))


def read_capture(
    path: Path, input_format: str = "auto"
) -> tuple[CaptureHeader | None, list[int]]:
    if input_format == "auto":
        if path.suffix.lower() == ".csv":
            input_format = "csv"
        elif path.read_bytes()[:4] == b"CAP2":
            input_format = "packet"
        else:
            input_format = "binary"
    if input_format == "packet":
        return parse_capture_packet(path.read_bytes())
    if input_format == "binary":
        return None, [value & 1 for value in path.read_bytes()]
    values: list[int] = []
    with path.open(newline="") as stream:
        for row in csv.reader(stream):
            if not row or row[0].strip().lower() in {"sample", "index"}:
                continue
            values.append(int(row[-1].strip(), 0) & 1)
    return None, values


def write_csv(samples: list[int], path: Path) -> None:
    with path.open("w", newline="") as stream:
        writer = csv.writer(stream)
        writer.writerow(["index", "scope"])
        writer.writerows((index, sample & 1) for index, sample in enumerate(samples))


def write_vcd(samples: list[int], path: Path, sample_div: int) -> None:
    if sample_div <= 0:
        raise ValueError("sample_div must be positive")
    step_ns = sample_div * 10
    with path.open("w", newline="\n") as stream:
        stream.write("$date generated by capture_dump.py $end\n")
        stream.write("$version RV32 Real-Time Digital Scope v2.0 $end\n")
        stream.write("$timescale 1ns $end\n$scope module scope $end\n")
        stream.write("$var wire 1 ! scope $end\n")
        stream.write("$upscope $end\n$enddefinitions $end\n$dumpvars\n")
        previous = None
        for index, sample in enumerate(samples):
            value = sample & 1
            stream.write(f"#{index * step_ns}\n")
            if previous is None or value != previous:
                stream.write(f"{value}!\n")
            previous = value
        stream.write("$dumpoff\n$end\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument(
        "--format", choices=("auto", "packet", "binary", "csv"), default="auto"
    )
    parser.add_argument(
        "--sample-div",
        type=int,
        help="required only for legacy binary/CSV inputs; CAP2 embeds this value",
    )
    parser.add_argument(
        "--csv",
        type=Path,
        help="optionally export the decoded single-channel samples as CSV",
    )
    args = parser.parse_args()
    header, samples = read_capture(args.input, args.format)
    sample_div = header.sample_div if header else args.sample_div
    if sample_div is None:
        parser.error("--sample-div is required for inputs without a CAP2 header")
    if args.csv:
        write_csv(samples, args.csv)
    write_vcd(samples, args.output, sample_div)
    csv_note = f", CSV -> {args.csv}" if args.csv else ""
    print(
        f"VCD PASS: {len(samples)} samples, {sample_div * 10} ns/step "
        f"-> {args.output}{csv_note}"
    )


if __name__ == "__main__":
    main()
